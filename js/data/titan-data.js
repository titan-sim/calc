// 타이탄(보스) 레벨별 공격력/체력 데이터
// 레벨 1~6: 실측 미확보 구간(레벨 5 제외) - 기존 값 그대로 유지.
// 레벨 5: 실측 결과 13,125,000(레벨 7 이후와 같은 계열의 공식값) - 기존 lv≤6 공식(2,500,000×레벨)
// 으로는 12,500,000이 나와 어긋나서 예외로 고정.
// 레벨 7~150: 실측(19개 지점, 레벨 5·7·12·15·17~22·30·39·40·42·47·75·77·124·138)으로 재검산한
// 결과, 레벨 39까지는 레벨당 +3,750,000, 레벨 40부터는 레벨당 +5,000,000으로 증가폭이 매끄럽게
// 바뀜 - 예전엔 "51레벨에서 티어 점프(+18,750,000)"로 가정했었는데 실제로는 그런 점프가 없고
// 39/40 경계에서 증가폭만 바뀌는 것으로 확인됨(42/47/75/77/124/138 실측치가 전부 이 가정과
// 정확히 일치, 51레벨 근처는 오히려 데이터가 부족해서 생긴 잘못된 티어 가정이었음). 게임 엔진이
// 32비트 부동소수점(Float32)으로 매 레벨 값을 그대로 누적 계산해서 반올림 오차가 남는데(레벨 39
// 부터 나타나기 시작해서 레벨이 오를수록 커짐 - 끝자리가 008 -> 024로 변함), 최종값 한 번만
// 반올림해선 이 패턴이 재현 안 되고 레벨 7부터 매 레벨 Math.fround를 누적 적용해야 실측치와
// 정확히 일치함(19개 지점 전부 확인됨). 138레벨 이후(139~150)는 실측치가 없어 같은 증가폭이
// 안 끊기고 이어진다고 가정한 추정값 - 나중에 실측치가 오면 다시 검산 필요.
function buildTitanStats() {
  const titanStats = [];
  for (let lv = 1; lv <= 6; lv++) {
    titanStats[lv] = { atk: lv * 5, hp: lv === 5 ? 13125000 : 2500000 * lv };
  }

  let hp = Math.fround(20625000);
  for (let lv = 7; lv <= 150; lv++) {
    if (lv > 7) hp = Math.fround(hp + (lv <= 39 ? 3750000 : 5000000));
    const atk = lv <= 10 ? 30 + (lv - 6) * 15 : 90 + (lv - 10) * 15;
    titanStats[lv] = { atk, hp };
  }
  return titanStats;
}

const TITAN_STATS = buildTitanStats();
